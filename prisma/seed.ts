async function main() {
  for (let i = 0; i < samples.length; i++) {
    const [
      customerName,
      customerEmail,
      reference,
      orderNumber,
      orderItemId,
      itemName,
      itemSku,
      reason,
      description,
      status,
    ] = samples[i] as [
      string,
      string,
      string,
      string,
      string,
      string,
      string,
      string,
      string,
      RequestStatus,
    ];
    const resolution =
      status === RequestStatus.APPROVED || status === RequestStatus.COMPLETED
        ? i % 2 === 0
          ? ResolutionType.REFUND
          : ResolutionType.REPLACEMENT
        : null;
    const productPrice = Number((49.99 + i * 17.35).toFixed(2));
    await prisma.returnRequest.upsert({
      where: { reference },
      update: { productPrice },
      create: {
        productPrice,
        customerName,
        customerEmail,
        reference,
        orderNumber,
        orderItemId,
        itemName,
        itemSku,
        reason,
        description,
        status,
        quantity: 1,
        ...(resolution
          ? {
              resolution,
              ...(resolution === ResolutionType.REFUND
                ? { refundAmount: 24.95 + i }
                : {}),
            }
          : {}),
        createdAt: new Date(Date.now() - i * 5 * 60 * 60 * 1000),
        notes: {
          create: [
            {
              body:
                status === RequestStatus.OPEN
                  ? "Request received; awaiting initial review."
                  : "Sample case created for workflow testing.",
              author: "Seed data",
            },
          ],
        },
        events: {
          create: [
            {
              type: RequestEventType.CREATED,
              message: "Seeded sample request.",
            },
          ],
        },
      },
    });
  }
  console.log(`Seeded ${samples.length} return request records.`);
}

main().finally(async () => prisma.$disconnect());
